// Builds engine/routes.gen.ts: every app/api route the browser engine serves.
import fs from "node:fs";
import path from "node:path";

const API = path.resolve("app/api");
const SKIP = [/^auth\//];
const OVERRIDE = { "img/[name]": "../engine/img" };
const found = [];
(function walk(dir, rel) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) walk(path.join(dir, e.name), rel ? `${rel}/${e.name}` : e.name);
    else if (e.name === "route.ts") found.push(rel);
  }
})(API, "");
const routes = found.filter((r) => !SKIP.some((s) => s.test(r))).sort();
const lines = ["// generated by scripts/gen-engine-routes.mjs — do not edit", "/* eslint-disable */"];
routes.forEach((r, i) => lines.push(`import * as m${i} from ${JSON.stringify(OVERRIDE[r] ? OVERRIDE[r] : `../app/api/${r}/route`)};`));
lines.push("export const ROUTES: { pattern: string; mod: Record<string, any> }[] = [");
routes.forEach((r, i) => lines.push(`  { pattern: ${JSON.stringify("/api/" + r)}, mod: m${i} as any },`));
lines.push("];");
fs.writeFileSync("engine/routes.gen.ts", lines.join("\n") + "\n");
console.log(routes.length, "routes");
